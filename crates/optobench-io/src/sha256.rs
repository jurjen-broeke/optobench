//! SHA-256 (FIPS 180-4), for the checksums in provenance records.
//!
//! Written from the specification (NIST FIPS PUB 180-4, Secure Hash Standard, 2015,
//! §4.1.2, §4.2.2, §5.1.1, §6.2) so the checksum needs no dependency. Not for secrets;
//! it identifies files.

/// Round constants: the first 32 bits of the fractional parts of the cube roots of the
